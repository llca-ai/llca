#!/bin/sh
# Build a source archive and a local Homebrew formula for llca.
# Usage: sh scripts/package.sh        (from the repository root)
# Then:  brew reinstall local/llca/llca   (or brew install …)
# Nothing is published: the formula points to the local archive.
set -eu
cd "$(dirname "$0")/.."
ROOT=$(pwd)
VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)
NAME="llca-$VERSION"

cargo test --release --quiet
mkdir -p dist Formula
STAGE=$(mktemp -d)
mkdir "$STAGE/$NAME"
cp -R Cargo.toml Cargo.lock README.md CONTRIBUTING.md SECURITY.md LICENSE src static rules "$STAGE/$NAME/"
tar -czf "dist/$NAME.tar.gz" -C "$STAGE" "$NAME"
rm -rf "$STAGE"

if command -v shasum >/dev/null 2>&1; then
  SHA=$(shasum -a 256 "dist/$NAME.tar.gz" | cut -d' ' -f1)
else
  SHA=$(sha256sum "dist/$NAME.tar.gz" | cut -d' ' -f1)
fi
URL="file://$(printf '%s' "$ROOT/dist/$NAME.tar.gz" | sed 's/ /%20/g')"

cat > Formula/llca.rb <<RUBY
# Generated by scripts/package.sh. For distribution, replace the file URL
# with a release URL and its SHA256.
class Llca < Formula
  desc "Local Ledger for Coding Agents (Codex, Claude Code)"
  license "MIT"
  url "$URL"
  version "$VERSION"
  sha256 "$SHA"
  depends_on "rust" => :build
  uses_from_macos "sqlite"

  def install
    system "cargo", "install", *std_cargo_args
  end

  test do
    assert_equal "$VERSION", shell_output("#{bin}/llca --version").strip
  end
end
RUBY

echo "Archive:  dist/$NAME.tar.gz"
echo "Formula:  Formula/llca.rb"

# Copy the formula into the local tap and drop any cached archive, so that
# brew always builds the archive that was just created.
if command -v brew >/dev/null 2>&1; then
  if ! brew --repository local/llca >/dev/null 2>&1 || [ ! -d "$(brew --repository local/llca)" ]; then
    brew tap-new --no-git local/llca >/dev/null
  fi
  TAP=$(brew --repository local/llca)
  mkdir -p "$TAP/Formula"
  cp Formula/llca.rb "$TAP/Formula/llca.rb"
  rm -f "$(brew --cache local/llca/llca 2>/dev/null)" 2>/dev/null || true
  echo "Tap updated. Next: brew reinstall local/llca/llca"
fi
