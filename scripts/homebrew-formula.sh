#!/bin/sh
# Prints the Homebrew formula for a release of llca, which installs the
# prebuilt binary of that release (no Rust, no compilation):
#
#   sh scripts/homebrew-formula.sh 0.7.7 > ../homebrew-tap/Formula/llca.rb
#
# The SHA-256 of each archive comes from the release's .sha256 files: read
# from DIR when given (the release workflow passes dist/), otherwise
# downloaded from the GitHub release, which must then be published.
set -eu
VERSION="${1:?usage: sh scripts/homebrew-formula.sh VERSION [DIR]}"
DIR="${2:-}"
BASE="https://github.com/llca-ai/llca/releases/download/v$VERSION"

sha() {
  name="llca-$VERSION-$1.tar.gz"
  if [ -n "$DIR" ]; then
    line=$(cat "$DIR/$name.sha256")
  else
    line=$(curl -fsSL "$BASE/$name.sha256")
  fi
  sum=${line%% *}
  case "$sum" in
    *[!0-9a-f]* | "") echo "No SHA-256 for $name" >&2; exit 1 ;;
  esac
  [ ${#sum} -eq 64 ] || { echo "No SHA-256 for $name" >&2; exit 1; }
  printf '%s' "$sum"
}

MAC_ARM=$(sha aarch64-apple-darwin)
MAC_INTEL=$(sha x86_64-apple-darwin)
LINUX_ARM=$(sha aarch64-unknown-linux-gnu)
LINUX_INTEL=$(sha x86_64-unknown-linux-gnu)

cat <<EOF
# Generated by scripts/homebrew-formula.sh in llca-ai/llca. Do not edit by hand:
# each release of llca updates this file.
class Llca < Formula
  desc "Local Ledger for Coding Agents: a private log of what Codex and Claude Code do"
  homepage "https://github.com/llca-ai/llca"
  version "$VERSION"
  license "MIT"

  on_macos do
    on_arm do
      url "$BASE/llca-$VERSION-aarch64-apple-darwin.tar.gz"
      sha256 "$MAC_ARM"
    end
    on_intel do
      url "$BASE/llca-$VERSION-x86_64-apple-darwin.tar.gz"
      sha256 "$MAC_INTEL"
    end
  end

  on_linux do
    on_arm do
      url "$BASE/llca-$VERSION-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$LINUX_ARM"
    end
    on_intel do
      url "$BASE/llca-$VERSION-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$LINUX_INTEL"
    end
  end

  def install
    bin.install "llca"
  end

  def caveats
    <<~EOS
      Install the hooks for Codex and Claude Code:
        llca init --global
      Then check that everything works:
        llca doctor
      After each upgrade, run \`llca init --global\` again.
    EOS
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/llca --version").strip
  end
end
EOF
