//! The local dashboard: a small HTTP server on 127.0.0.1, started only by
//! `llca open` (or `demo`) and stopped with Ctrl+C. The API requires a
//! token created for each launch, and checks the Host and Origin headers.

use std::fs;
use std::io::{Read, Write};
use std::net::{TcpListener, TcpStream};
use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::Duration;

use crate::install;
use crate::json::{Map, Value};
use crate::obj;
use crate::store::{self, Filter};
use crate::util;

const INDEX: &str = include_str!("../static/index.html");
const APP_JS: &str = include_str!("../static/app.js");
const STYLE: &str = include_str!("../static/style.css");
/// Service logos (generated by scripts/brands.py from rules/services.rules).
const BRANDS_JS: &str = include_str!("../static/brands.js");
/// File in the data folder holding the dashboard theme chosen by the user
/// ("light" or "dark"; absent means Auto, which follows the Mac).
const THEME_FILE: &str = "dashboard-theme";
const CSP: &str = "default-src 'self'; script-src 'self'; style-src 'self'; connect-src 'self'; img-src 'self' blob:; frame-ancestors 'none'; base-uri 'none'; form-action 'none'";

pub struct Dashboard {
    pub data_dir: PathBuf,
    /// Agent → configuration directory, used to report installation status.
    pub targets: Vec<(String, PathBuf)>,
    pub demo: bool,
    pub token: String,
    pub port: u16,
    /// The last overviews computed, with the state of the files they were
    /// computed from: the dashboard asks every 4 s, and most of the time
    /// nothing changed (see `journal_state`).
    pub overviews: std::sync::Mutex<Vec<(String, JournalState, Arc<String>)>>,
}

type JournalState = Vec<Option<(u64, std::time::SystemTime)>>;

/// Size and modification time of every file an overview depends on: the
/// journal, its WAL (every write lands there first) and watch.rules.
fn journal_state(data_dir: &Path) -> JournalState {
    ["events.sqlite3", "events.sqlite3-wal", crate::watch::FILE_NAME]
        .iter()
        .map(|name| std::fs::metadata(data_dir.join(name)).ok().and_then(|m| Some((m.len(), m.modified().ok()?))))
        .collect()
}

struct Request {
    method: String,
    path: String,
    query: String,
    headers: Vec<(String, String)>,
}

impl Request {
    fn header(&self, name: &str) -> Option<&str> {
        self.headers.iter().find(|(k, _)| k.eq_ignore_ascii_case(name)).map(|(_, v)| v.as_str())
    }
}

fn read_request(stream: &mut TcpStream) -> Option<Request> {
    stream.set_read_timeout(Some(Duration::from_secs(5))).ok()?;
    let mut buf = Vec::new();
    let mut chunk = [0u8; 4096];
    while !buf.windows(4).any(|w| w == b"\r\n\r\n") {
        let n = stream.read(&mut chunk).ok()?;
        if n == 0 || buf.len() > 64 * 1024 {
            return None;
        }
        buf.extend_from_slice(&chunk[..n]);
    }
    let head = String::from_utf8_lossy(&buf);
    let mut lines = head.split("\r\n");
    let mut first = lines.next()?.split(' ');
    let method = first.next()?.to_string();
    let target = first.next()?.to_string();
    let (path, query) = target.split_once('?').map(|(p, q)| (p.to_string(), q.to_string())).unwrap_or((target, String::new()));
    let headers = lines.take_while(|l| !l.is_empty()).filter_map(|l| l.split_once(':')).map(|(k, v)| (k.trim().to_string(), v.trim().to_string())).collect();
    Some(Request { method, path, query, headers })
}

fn percent_decode(s: &str) -> String {
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        let hex = bytes.get(i + 1..i + 3).and_then(|h| std::str::from_utf8(h).ok()).and_then(|h| u8::from_str_radix(h, 16).ok());
        match (bytes[i], hex) {
            (b'+', _) => out.push(b' '),
            (b'%', Some(b)) => {
                out.push(b);
                i += 2;
            }
            (b, _) => out.push(b),
        }
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// First non-empty value of a query parameter (blank values are ignored, like
/// Python's `parse_qs`).
fn param(query: &str, name: &str) -> String {
    query
        .split('&')
        .filter_map(|pair| pair.split_once('='))
        .find(|(k, v)| percent_decode(k) == name && !v.is_empty())
        .map(|(_, v)| percent_decode(v))
        .unwrap_or_default()
}

/// Agent, time range and project, shared by the event list and the overview.
/// Times must look like stored timestamps (digits, T, :, ., +, -, Z).
fn scope_params(query: &str) -> Option<(String, String, String, String)> {
    let (from, to) = (param(query, "from"), param(query, "to"));
    let timestamp = |t: &str| t.len() <= 40 && t.chars().all(|c| c.is_ascii_digit() || "T:.+-Z".contains(c));
    if !timestamp(&from) || !timestamp(&to) {
        return None;
    }
    Some((param(query, "agent"), from, to, param(query, "project")))
}

fn respond(stream: &mut TcpStream, status: u16, body: &[u8], mime: &str) {
    let reason = match status {
        200 => "OK",
        204 => "No Content",
        400 => "Bad Request",
        401 => "Unauthorized",
        403 => "Forbidden",
        404 => "Not Found",
        405 => "Method Not Allowed",
        _ => "Internal Server Error",
    };
    let head = format!(
        "HTTP/1.1 {status} {reason}\r\nContent-Type: {mime}\r\nContent-Length: {}\r\nCache-Control: no-store\r\nX-Content-Type-Options: nosniff\r\nReferrer-Policy: no-referrer\r\nContent-Security-Policy: {CSP}\r\nConnection: close\r\n\r\n",
        body.len()
    );
    let _ = stream.write_all(head.as_bytes());
    let _ = stream.write_all(body);
    let _ = stream.flush();
}

fn json(stream: &mut TcpStream, status: u16, value: Value) {
    respond(stream, status, value.to_compact().as_bytes(), "application/json; charset=utf-8");
}

fn error(stream: &mut TcpStream, status: u16, message: &str) {
    json(stream, status, obj![("error", message)]);
}

impl Dashboard {
    /// The saved theme: "light", "dark", or "auto" when none (or anything else) is saved.
    fn theme(&self) -> &'static str {
        match fs::read_to_string(self.data_dir.join(THEME_FILE)).unwrap_or_default().trim() {
            "light" => "light",
            "dark" => "dark",
            _ => "auto",
        }
    }

    fn handle(&self, mut stream: TcpStream) {
        let Some(req) = read_request(&mut stream) else { return };
        let origin = format!("127.0.0.1:{}", self.port);
        if req.header("Host") != Some(origin.as_str()) {
            return error(&mut stream, 403, "Host rejected");
        }
        if req.header("Origin").is_some_and(|o| o != format!("http://{origin}")) {
            return error(&mut stream, 403, "Origin rejected");
        }
        // Only these actions change anything, and only by POST.
        let writes = matches!(req.path.as_str(), "/api/secret-alert/dismiss" | "/api/secret-alert/restore" | "/api/watch/open" | "/api/theme");
        if req.method != if writes { "POST" } else { "GET" } {
            return error(&mut stream, 405, "Method not allowed");
        }
        if req.path.starts_with("/api/") {
            let supplied = req.header("Authorization").unwrap_or_default();
            if !util::same_secret(supplied.as_bytes(), format!("Bearer {}", self.token).as_bytes()) {
                return error(&mut stream, 401, "Open the URL printed by llca open");
            }
            return match req.path.as_str() {
                "/api/events" => {
                    let before = match param(&req.query, "before").as_str() {
                        "" => 0,
                        text => match text.parse::<i64>() {
                            Ok(n) => n,
                            Err(_) => return error(&mut stream, 400, "Invalid parameter"),
                        },
                    };
                    let (q, category, session, service) = (param(&req.query, "q"), param(&req.query, "category"), param(&req.query, "session"), param(&req.query, "service"));
                    let (rule, kind, result) = (param(&req.query, "rule"), param(&req.query, "kind"), param(&req.query, "result"));
                    let Some((agent, from, to, project)) = scope_params(&req.query) else {
                        return error(&mut stream, 400, "Invalid parameter");
                    };
                    if !(kind.is_empty() || store::KINDS.contains(&kind.as_str())) || !(result.is_empty() || store::RESULTS.contains(&result.as_str())) {
                        return error(&mut stream, 400, "Invalid parameter");
                    }
                    let filter = Filter { search: &q, category: &category, session: &session, agent: &agent, before, limit: 200, from: &from, to: &to, project: &project, service: &service, rule: &rule, kind: &kind, result: &result };
                    match store::query(&self.data_dir, &filter) {
                        Ok(page) => json(
                            &mut stream,
                            200,
                            obj![("events", Value::Array(page.events)), ("next", page.next.map_or(Value::Null, Value::int)), ("scanned", Value::int(page.scanned as i64))],
                        ),
                        Err(_) => error(&mut stream, 500, "Log unavailable"),
                    }
                }
                "/api/overview" => {
                    let Some((agent, from, to, project)) = scope_params(&req.query) else {
                        return error(&mut stream, 400, "Invalid parameter");
                    };
                    let tz = match param(&req.query, "tz").as_str() {
                        "" => 0,
                        text => match text.parse::<i64>() {
                            Ok(n) if n.abs() <= 14 * 60 => n,
                            _ => return error(&mut stream, 400, "Invalid parameter"),
                        },
                    };
                    let filter = Filter { agent: &agent, from: &from, to: &to, project: &project, ..Default::default() };
                    let key = req.query.clone();
                    let before = journal_state(&self.data_dir);
                    let cached = self.overviews.lock().ok().and_then(|c| c.iter().find(|(k, s, _)| *k == key && *s == before).map(|(_, _, body)| body.clone()));
                    if let Some(body) = cached {
                        return respond(&mut stream, 200, body.as_bytes(), "application/json; charset=utf-8");
                    }
                    match store::overview(&self.data_dir, &filter, tz, param(&req.query, "commands") != "0") {
                        Ok(v) => {
                            let body = Arc::new(v.to_compact());
                            // Kept only if nothing was written meanwhile.
                            if journal_state(&self.data_dir) == before {
                                if let Ok(mut c) = self.overviews.lock() {
                                    c.retain(|(k, _, _)| *k != key);
                                    c.insert(0, (key, before, body.clone()));
                                    c.truncate(6);
                                }
                            }
                            respond(&mut stream, 200, body.as_bytes(), "application/json; charset=utf-8")
                        }
                        Err(_) => error(&mut stream, 500, "Log unavailable"),
                    }
                }
                "/api/secret-alert/dismiss" => {
                    let Some((agent, from, to, project)) = scope_params(&req.query) else {
                        return error(&mut stream, 400, "Invalid parameter");
                    };
                    let Ok(through) = param(&req.query, "through").parse::<i64>() else {
                        return error(&mut stream, 400, "Invalid parameter");
                    };
                    let filter = Filter { agent: &agent, from: &from, to: &to, project: &project, ..Default::default() };
                    match store::dismiss_secrets(&self.data_dir, &filter, through) {
                        Ok(batch) => json(&mut stream, 200, obj![("batch", Value::int(batch))]),
                        Err(_) => error(&mut stream, 500, "Log unavailable"),
                    }
                }
                // Your rules: open watch.rules in the default text editor,
                // creating it with its examples first if needed. The path is
                // fixed: nothing in the request names a file.
                "/api/watch/open" => {
                    if crate::watch::create_if_missing(&self.data_dir).is_err() {
                        return error(&mut stream, 500, "Could not create the rules file");
                    }
                    // `?show=finder`: show the file in Finder instead (the
                    // Library folder is hidden there).
                    let reveal = param(&req.query, "show") == "finder";
                    match open_text_file(&self.data_dir.join(crate::watch::FILE_NAME), reveal) {
                        Ok(()) => json(&mut stream, 200, obj![("opened", true)]),
                        Err(reason) => error(&mut stream, 500, &format!("Could not open the rules file: {reason}")),
                    }
                }
                "/api/secret-alert/restore" => {
                    let Ok(batch) = param(&req.query, "batch").parse::<i64>() else {
                        return error(&mut stream, 400, "Invalid parameter");
                    };
                    match store::restore_secrets(&self.data_dir, batch) {
                        Ok(()) => json(&mut stream, 200, obj![("restored", true)]),
                        Err(_) => error(&mut stream, 500, "Log unavailable"),
                    }
                }
                "/api/status" => {
                    let mut installation = Map::new();
                    for (agent, target) in &self.targets {
                        let state = install::inspect(&self.data_dir, target, agent)
                            .unwrap_or_else(|_| obj![("installed", false), ("note", "Unreadable configuration")]);
                        installation.insert(agent.clone(), state);
                    }
                    match store::stats(&self.data_dir) {
                        Ok(stats) => json(
                            &mut stream,
                            200,
                            obj![
                                ("stats", stats),
                                ("installation", Value::Object(installation)),
                                ("collector", if self.demo { Value::Null } else { install::collector_state(&self.data_dir) }),
                                ("demo", self.demo),
                                ("data_dir", self.data_dir.to_string_lossy().into_owned()),
                            ],
                        ),
                        Err(_) => error(&mut stream, 500, "Log unavailable"),
                    }
                }
                // The theme chosen in the dashboard: auto, light or dark.
                "/api/theme" => {
                    let path = self.data_dir.join(THEME_FILE);
                    let saved = match param(&req.query, "set").as_str() {
                        "auto" => fs::remove_file(&path).or_else(|e| if e.kind() == std::io::ErrorKind::NotFound { Ok(()) } else { Err(e) }),
                        theme @ ("light" | "dark") => util::atomic_write(&path, theme.as_bytes(), 0o600),
                        _ => return error(&mut stream, 400, "Invalid parameter"),
                    };
                    match saved {
                        Ok(()) => json(&mut stream, 200, obj![("theme", self.theme())]),
                        Err(_) => error(&mut stream, 500, "Could not save the theme"),
                    }
                }
                "/api/app-icon" => {
                    let name = param(&req.query, "name");
                    if !crate::icons::valid_name(&name) {
                        return error(&mut stream, 400, "Invalid parameter");
                    }
                    match crate::icons::png(&self.data_dir, &name) {
                        Some(bytes) => respond(&mut stream, 200, &bytes, "image/png"),
                        // No icon is a normal answer, not an error: 204 keeps the console clean.
                        None => respond(&mut stream, 204, b"", "image/png"),
                    }
                }
                _ => error(&mut stream, 404, "Not found"),
            };
        }
        match req.path.as_str() {
            "/" => respond(&mut stream, 200, INDEX.as_bytes(), "text/html; charset=utf-8"),
            "/app.js" => respond(&mut stream, 200, APP_JS.as_bytes(), "text/javascript; charset=utf-8"),
            "/style.css" => respond(&mut stream, 200, STYLE.as_bytes(), "text/css; charset=utf-8"),
            // Loaded before the stylesheet, so a saved theme applies before the first paint.
            "/theme.js" => {
                let script = match self.theme() {
                    "auto" => "// Auto: the page follows the Mac.\n".to_string(),
                    theme => format!("document.documentElement.dataset.theme = \"{theme}\";\n"),
                };
                respond(&mut stream, 200, script.as_bytes(), "text/javascript; charset=utf-8")
            }
            "/brands.js" => respond(&mut stream, 200, BRANDS_JS.as_bytes(), "text/javascript; charset=utf-8"),
            _ => error(&mut stream, 404, "Not found"),
        }
    }
}

/// Bind the dashboard. Returns the listener and its URL (with the token).
pub fn bind(data_dir: &Path, targets: Vec<(String, PathBuf)>, port: u16, demo: bool) -> std::io::Result<(TcpListener, Arc<Dashboard>, String)> {
    let listener = TcpListener::bind(("127.0.0.1", port))?;
    let port = listener.local_addr()?.port();
    let token = util::base64url(&util::random_bytes(32)?);
    let url = format!("http://127.0.0.1:{port}/#token={token}");
    let dashboard = Arc::new(Dashboard { data_dir: data_dir.to_path_buf(), targets, demo, token, port, overviews: Default::default() });
    Ok((listener, dashboard, url))
}

/// Serve until Ctrl+C (or until `stop` returns true).
pub fn serve_until(listener: TcpListener, dashboard: Arc<Dashboard>, stop: impl Fn() -> bool) -> std::io::Result<()> {
    listener.set_nonblocking(true)?;
    while !stop() {
        match listener.accept() {
            Ok((stream, _)) => {
                let _ = stream.set_nonblocking(false);
                let d = Arc::clone(&dashboard);
                std::thread::spawn(move || d.handle(stream));
            }
            Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => std::thread::sleep(Duration::from_millis(40)),
            Err(e) => return Err(e),
        }
    }
    Ok(())
}

/// Open a text file in the default text editor (macOS: `open -t`).
/// Open a file in a text editor, or show it in Finder (`reveal`). Returns
/// the reason when it fails (the message of `open`, shown in the dashboard).
/// macOS: the default text editor (`open -t`), then TextEdit (`open -e`) if
/// no default is set for plain text.
fn open_text_file(path: &Path, reveal: bool) -> Result<(), String> {
    let attempts: Vec<(&str, Vec<&str>)> = if cfg!(target_os = "macos") {
        if reveal { vec![("open", vec!["-R"])] } else { vec![("open", vec!["-t"]), ("open", vec!["-e"])] }
    } else {
        vec![("xdg-open", vec![])]
    };
    let mut reason = String::from("no program to open it");
    for (program, flags) in attempts {
        let out = std::process::Command::new(program).args(flags).arg(path).stdin(std::process::Stdio::null()).output();
        match out {
            Ok(o) if o.status.success() => return Ok(()),
            Ok(o) => reason = String::from_utf8_lossy(&o.stderr).lines().next().unwrap_or("it did not open").chars().take(200).collect(),
            Err(e) => reason = format!("{program}: {e}"),
        }
    }
    Err(reason)
}

pub fn open_browser(url: &str) {
    let opener = if cfg!(target_os = "macos") { "open" } else { "xdg-open" };
    let _ = std::process::Command::new(opener)
        .arg(url)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn();
}
